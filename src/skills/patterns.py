"""Шаблоны со слотами (L1) — параметрические команды без 3B.

Уровни распознавания речи в команду:

  L0  ``match_alias``  — ТОЧНАЯ фраза → навык («терминал», «тише»). Микросекунды.
  L1  ``match`` (здесь) — фраза-ШАБЛОН с аргументом → навык + извлечённый слот
                          («громкость 30», «быстрый скан 10.0.0.1»). Детерминирован.
  L2  ``IntentRouter`` → 3B — настоящий хвост: парафраз, неоднозначность, разговор.

Боль, которую закрывает L1: ``match_alias`` ловит только ТОЧНОЕ совпадение, поэтому
любая команда с аргументом («громкость 30», «скан 192.168.1.1») раньше уходила на
3B — а это и медленно, и именно там модель чаще всего ошибалась в извлечении слота.
L1 ловит параметрический КЛАСС команд заранее написанным regex с именованными
группами (= имена args навыка) и зовёт выверенный навык напрямую.

Принципы (наследуем философию alias fast-path — высокая точность, ноль ложных
срабатываний на curated-наборе):

  * ``re.fullmatch`` по НОРМАЛИЗОВАННОЙ фразе — шаблон должен покрыть всю реплику,
    а не «найтись где-то внутри». Это режет ложные срабатывания.
  * Имена групп шаблона ⊆ ``params`` целевого навыка (стережёт тест-инвариант
    ``tests/test_pattern_fastpath.py`` — дрейф каталога ломает сборку, не прод).
  * Слоты передаются СТРОКАМИ; коэрцию/валидацию делает сам навык
    (``_clamp_pct`` для процентов, ``_TARGET_RE`` для цели скана) — L1 не дублирует
    бизнес-логику, лишь извлекает текст.
  * Числительные словами («двадцать пять») → цифры до матчинга: Vosk нередко
    отдаёт число словами, а захардкоженный ``\\d`` иначе бы их не поймал.

Параметризованные фразы намеренно НЕ матчатся ``match_alias`` (см. его docstring) —
этот модуль и есть их законный обработчик ступенью ниже 3B.
"""
from __future__ import annotations

import logging
import re
from dataclasses import dataclass

from src.skills import apps
from src.skills.registry import normalize_phrase

log = logging.getLogger("jarvis.patterns")


# ─────────────────────────── Числительные словами → цифры ───────────────────────────
# 0..100 — диапазон процентов громкости/яркости. Vosk-ru часто выдаёт число
# словами; сворачиваем непрерывный прогон числительных в одно число (русский
# составной счёт 0..100 аддитивен: «двадцать пять» = 20+5, «сто» = 100).
_NUM_WORDS: dict[str, int] = {
    "ноль": 0,
    "один": 1, "одна": 1, "одно": 1,
    "два": 2, "две": 2, "три": 3, "четыре": 4, "пять": 5,
    "шесть": 6, "семь": 7, "восемь": 8, "девять": 9, "десять": 10,
    "одиннадцать": 11, "двенадцать": 12, "тринадцать": 13, "четырнадцать": 14,
    "пятнадцать": 15, "шестнадцать": 16, "семнадцать": 17, "восемнадцать": 18,
    "девятнадцать": 19,
    "двадцать": 20, "тридцать": 30, "сорок": 40, "пятьдесят": 50,
    "шестьдесят": 60, "семьдесят": 70, "восемьдесят": 80, "девяносто": 90,
    "сто": 100,
}


def digitize(text: str) -> str:
    """Свернуть прогоны русских числительных в цифры: «громкость двадцать пять»
    → «громкость 25». Не-числительные токены не трогает; цифры уже в тексте —
    проходят насквозь. Идемпотентна на тексте без числительных-слов."""
    out: list[str] = []
    run: int | None = None
    for tok in text.split():
        val = _NUM_WORDS.get(tok)
        if val is not None:
            run = (run or 0) + val
        else:
            if run is not None:
                out.append(str(run))
                run = None
            out.append(tok)
    if run is not None:
        out.append(str(run))
    return " ".join(out)


# ─────────────────────────── Описание шаблона ───────────────────────────
@dataclass(frozen=True, slots=True)
class SkillPattern:
    """Один параметрический шаблон.

    ``regex`` — компилированный, с именованными группами (= имена args навыка).
    ``reply`` — устная подтверждающая фраза с подстановкой слотов (``{percent}`` /
    ``{target}``); играется немедленно, параллельно действию (как reply модели в
    агентном пути). ``numeric`` — матчить по digitized-тексту (числительные →
    цифры); для текстовых слотов (цель скана) False, чтобы не покалечить хост/IP."""
    id: str
    skill_id: str
    regex: re.Pattern[str]
    reply: str
    numeric: bool = False


@dataclass(frozen=True, slots=True)
class PatternMatch:
    """Результат L1-матча: какой навык звать, с какими args, что сказать."""
    skill_id: str
    args: dict[str, str]
    reply: str


# ─────────────────────────── Конструкторы шаблонов ───────────────────────────
# Необязательный повелительный префикс и суффикс «процентов/%» — чтобы покрыть
# живые формулировки, оставаясь fullmatch (высокая точность).
_SET = r"(?:сделай |поставь |установи |выставь |задай |переключи )?"
_PCT = r"(?:\s*(?:процент\w*|%))?"
# Слот цели скана: host / IP / CIDR / диапазон. Уже нормализовано в lower-case;
# валидацию (анти-инъекция) делает сам навык pentest (_TARGET_RE).
_TARGET = r"(?P<target>[a-z0-9][a-z0-9_.:/-]{1,63})"


def _pct(keyword: str) -> str:
    """Шаблон «<глагол> <ключевое слово> [на] N [процентов]»."""
    return rf"{_SET}(?:{keyword})(?: на)? (?P<percent>\d{{1,3}}){_PCT}"


def _scan(keyword: str, link: str = r"(?: цели| хоста| адреса| подсети| на| в| по)?") -> str:
    """Шаблон «<пресет скана> [связка] <цель>»."""
    return rf"(?:{keyword}){link} {_TARGET}"


def _p(skill_id: str, body: str, reply: str, *, numeric: bool = False) -> SkillPattern:
    return SkillPattern(
        id=skill_id,
        skill_id=skill_id,
        regex=re.compile(body, re.IGNORECASE),
        reply=reply,
        numeric=numeric,
    )


# ─────────────────────────── Встроенные шаблоны ───────────────────────────
# Порядок = приоритет разрешения (первый fullmatch выигрывает). Ключевые слова
# пресетов попарно различны, поэтому пересечений между шаблонами нет.
_PATTERNS: tuple[SkillPattern, ...] = (
    # UI_CONTROL — проценты (числительные словами тоже ловим: numeric=True).
    _p("set_volume", _pct(r"громкость|громкости|звук|звука"),
       "Громкость на {percent} процентов, сэр.", numeric=True),
    _p("set_brightness", _pct(r"яркость|яркости|подсветк\w*"),
       "Яркость на {percent} процентов, сэр.", numeric=True),
    # PENTEST_RECON — цель скана (текстовый слот: numeric=False).
    _p("nmap_quick", _scan(r"быстрый скан|сканируй порты|просканируй порты|скан портов"),
       "Запускаю быстрый скан. Цель. {target}."),
    _p("nmap_service_scan", _scan(r"скан сервисов|сканируй сервисы|версии сервисов|что за сервисы"),
       "Сканирую сервисы цели {target}."),
    _p("nmap_ping_sweep", _scan(r"пинг подсети|пинг свип|кто в сети|живые хосты|кто жив"),
       "Проверяю, кто жив. Подсеть. {target}."),
    _p("nmap_top_ports", _scan(r"топ порты|топ портов|популярные порты|самые частые порты"),
       "Сканирую топ-порты цели {target}."),
)


# ─────────────────────────── L1a: «открой <приложение>» ───────────────────────────
# Глагол запуска + открытый слот-имя; резолвер (skills/apps.py) превращает имя в
# выверенную команду каталога. Открытый слот нельзя покрыть фиксированной фразой,
# поэтому это отдельная ступень: regex ловит ГЛАГОЛ, apps.resolve — СУЩНОСТЬ.
_OPEN_RE = re.compile(
    r"(?:ну |давай |а )?"
    r"(?:открой|открыть|запусти|запустить|запускай|вруби|врубай|включи|включить|стартуй)(?:-ка)?"
    r"(?: мне)?"
    r"(?: приложение| программу| прогу| прилу)?"
    r" (?P<app>.+?)"
    r"(?:\s+(?:пожалуйста|сэр|прошу|ка))?",
    re.IGNORECASE,
)


def _match_open(norm: str) -> PatternMatch | None:
    """L1a: «открой/запусти <имя>» → open_app(app=ключ), иначе None.

    Резолвер сам решает, узнал ли он приложение; None → интент уходит 3B (а не
    открывает наугад не то)."""
    m = _OPEN_RE.fullmatch(norm)
    if m is None:
        return None
    entry = apps.resolve(m.group("app"))
    if entry is None:
        return None
    log.info("pattern L1a: %r → open_app(%s)", norm[:60], entry.key)
    return PatternMatch(
        skill_id="open_app",
        args={"app": entry.key},
        reply=f"Открываю {entry.label}, сэр.",
    )


def match(text: str) -> PatternMatch | None:
    """Параметрический шаблон → (навык, извлечённые слоты, реплика), иначе None.

    Только ``fullmatch`` по нормализованной фразе — высокая точность, никаких
    ложных срабатываний на середине реплики. Числовые шаблоны матчатся по тексту
    с числительными-цифрами (digitize); текстовые — по «сырой» нормализации.
    Последней ступенью идёт L1a-резолвер приложений («открой X»)."""
    norm = normalize_phrase(text)
    if not norm:
        return None
    digits = digitize(norm)
    for pat in _PATTERNS:
        candidate = digits if pat.numeric else norm
        m = pat.regex.fullmatch(candidate)
        if m is None:
            continue
        args = {k: v for k, v in m.groupdict().items() if v is not None}
        try:
            reply = pat.reply.format(**args)
        except (KeyError, IndexError):
            reply = pat.reply
        log.info("pattern L1: %r → skill=%s args=%s", text[:60], pat.skill_id, args)
        return PatternMatch(skill_id=pat.skill_id, args=args, reply=reply)
    # L1a: открытый слот-приложение (резолвер синонимов + fuzzy).
    return _match_open(norm)


def all_patterns() -> tuple[SkillPattern, ...]:
    return _PATTERNS


